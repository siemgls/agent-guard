/**
 * Wire format between the browser script, the middleware and the scoring API.
 *
 * The client only sends aggregated counters, never raw keystrokes, answers or
 * mouse coordinates. That keeps the payload small and limits personal data.
 */

export interface EnvSignals {
  /** navigator.webdriver === true */
  webdriver: boolean;
  /** Names of known automation globals found on window/document */
  automationGlobals: string[];
  /** User agent contains "HeadlessChrome" or similar */
  headlessUA: boolean;
  /** window.outerWidth/outerHeight are 0 (common in headless) */
  zeroOuterSize: boolean;
  /** Primary pointer is coarse (touch). Mouse-based signals are skipped then. */
  touchPrimary: boolean;
}

/** Counters since the previous batch (deltas, summed by the API). */
export interface EventCounters {
  /** Events with isTrusted === false (dispatched by page JS / extensions) */
  untrusted: number;
  clicks: number;
  /** Clicks preceded by fewer than 2 pointer moves in the last 1000 ms */
  clicksWithoutMovement: number;
  /** Pointer moves of type "mouse" */
  mouseMoves: number;
  keydowns: number;
  /** Text inputs (insertText) with no keydown in the previous 100 ms */
  inputsWithoutKeydown: number;
  /** Subset of inputsWithoutKeydown that came through text composition (IME, possibly dictation) */
  composedInputs: number;
  compositionStarts: number;
  /** Key presses handled by an input method (keyCode 229) */
  processKeydowns: number;
  pastes: number;
  scrolls: number;
  /** Tab/window lost focus */
  blurs: number;
}

export interface TimingStats {
  /** Number of key intervals included in mean/variance below */
  keyIntervals: number;
  keyIntervalMean: number;
  keyIntervalM2: number;
  /** Mouse path straightness samples (0..1, 1 = perfectly straight) */
  pathSamples: number;
  pathStraightnessSum: number;
}

export interface SignalBatch {
  v: 1;
  /** Random session id generated by the client */
  sid: string;
  /** Batch sequence number within the session */
  seq: number;
  /** ms since the script loaded */
  t: number;
  /** Re-checked every batch: some automation globals appear late */
  env: EnvSignals;
  events: EventCounters;
  timing: TimingStats;
  /** Time from load to first trusted user interaction, ms (once known) */
  firstInteractionMs?: number;
}

export type Verdict = 'allow' | 'flag' | 'pause' | 'unknown';

export interface ScoreResult {
  sid: string;
  verdict: Verdict;
  /** 0..1, higher = more agent-like */
  score: number;
  /** Plain-language reasons, meant to be shown to a teacher */
  reasons: string[];
}
